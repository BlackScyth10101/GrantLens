# 5. [NEW WEEK 3] GEMINI AI NARRATIVE REVIEW ENTITY
# ==============================================================================

class AIReview(Base):
    """
    Represents an intelligent qualitative peer-review generated by Google Gemini.
    Evaluates the academic manuscript against federal solicitation rubrics:
    - Intellectual Merit Score (0.0 - 100.0)
    - Broader Impacts Score (0.0 - 100.0)
    - Solicitation Alignment Score (0.0 - 100.0)
    - Budget Feasibility Score (0.0 - 100.0)
    - Composite Overall Quality Score (0.0 - 100.0)
    - Qualitative SRO Consensus Executive Summary
    - Granular Section Critiques with side-by-side suggested revisions.
    """
    __tablename__ = "ai_reviews"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        index=True,
    )

    # Foreign key referencing parent grant submission
    submission_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("grant_submissions.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    # Exact Gemini model identifier employed (e.g. "gemini-1.5-flash")
    model_version: Mapped[str] = mapped_column(
        String(50),
        default="gemini-1.5-flash",
        nullable=False,
    )

    # --------------------------------------------------------------------------
    # NSF / NIH Rubric Sub-Scores
    # --------------------------------------------------------------------------
    intellectual_merit_score: Mapped[float] = mapped_column(
        Float,
        default=0.0,
        nullable=False,
    )

    broader_impacts_score: Mapped[float] = mapped_column(
        Float,
        default=0.0,
        nullable=False,
    )

    solicitation_alignment_score: Mapped[float] = mapped_column(
        Float,
        default=0.0,
        nullable=False,
    )

    budget_feasibility_score: Mapped[float] = mapped_column(
        Float,
        default=0.0,
        nullable=False,
    )

    # Weighted composite score
    overall_composite_score: Mapped[float] = mapped_column(
        Float,
        default=0.0,
        nullable=False,
    )

    # Simulated panel verdict: FUND_WITH_DISTINCTION | REVISE_AND_RESUBMIT | DO_NOT_RECOMMEND
    panel_recommendation: Mapped[str] = mapped_column(
        String(50),
        default="REVISE_AND_RESUBMIT",
        nullable=False,
    )

    # Formal executive summary written from the perspective of an SRO Panel Chair
    executive_summary: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )

    # Structured JSON containing section diagnoses and side-by-side rewrites:
    # [
    #   {
    #     "section_name": "Broader Impacts",
    #     "status": "NEEDS_IMPROVEMENT",
    #     "severity": "YELLOW",
    #     "score": 72.0,
    #     "identified_weakness": "...",
    #     "original_excerpt": "...",
    #     "suggested_rewrite": "...",
    #     "remediation_rationale": "..."
    #   }
    # ]
    section_critiques: Mapped[list[dict[str, Any]]] = mapped_column(
        JSON,
        nullable=False,
        default=list,
    )

    # Raw structured payload received from Gemini for auditing and reproduction
    raw_response: Mapped[dict[str, Any]] = mapped_column(
        JSON,
        nullable=False,
        default=dict,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    # Relationship back to GrantSubmission
    submission: Mapped["GrantSubmission"] = relationship(
        "GrantSubmission",
        back_populates="ai_reviews",
    )
