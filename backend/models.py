"""
================================================================================
GrantLens Compliance & Audit Engine - Relational ORM Models
================================================================================
Project: GrantLens (CSE299 Section 3, Group 2)
Milestone: Week 3 - Gemini AI API Integration & Dual Compliance Evaluation
Author: Hasin Anzum Inan, Anas Ibne Majbha, Tazreen Alam, Israt Jahan Susmi
================================================================================
This module defines the relational schema using SQLAlchemy 2.0 Declarative Mapped
columns. It supports both PostgreSQL 16 (in containerized production) and SQLite
(with aiosqlite for local development and test fixtures).

Schema Organization:
- User: Academic researchers and institutional research administration accounts.
- GrantSubmission: Central parent entity linking submitted proposals with audits.
- Document: Uploaded PDF artifacts (Solicitation calls vs Draft proposals) with
  PyMuPDF extracted geometry metadata and cryptographic SHA-256 hashes.
- AuditReport & AuditFinding: Week 2 deterministic heuristic rule engine results
  (page limits, sub-millimeter margins, min font sizes, required sections).
- BudgetLineItem: Granular financial table items extracted via pdfplumber.
- [NEW Week 3] AIReview: Deep narrative evaluations generated by Google Gemini
  (gemini-1.5-flash), including NSF/NIH rubric scores, panel recommendations,
  weakness diagnoses, and side-by-side publication-grade section rewrites.
================================================================================
"""

import enum
import uuid
from datetime import datetime
from decimal import Decimal
from typing import Any, List, Optional
from sqlalchemy import (
    Boolean,
    DateTime,
    Enum,
    Float,
    ForeignKey,
    Index,
    Integer,
    Numeric,
    String,
    Text,
    func,
)
from sqlalchemy.types import JSON, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship
from database import Base


# ==============================================================================
# ENUMERATIONS (Type safety for database columns)
# ==============================================================================

class DocumentType(str, enum.Enum):
    """
    Distinguishes the document classification for ingested PDFs:
    - SOLICITATION: The agency call/guideline (e.g. NSF 24-500, NIH R01, DOE)
    - DRAFT_PROPOSAL: The researcher's manuscript being submitted for pre-flight audit.
    """
    SOLICITATION = "SOLICITATION"
    DRAFT_PROPOSAL = "DRAFT_PROPOSAL"


class AuditStatus(str, enum.Enum):
    """
    Overall compliance verdict for an audited grant submission:
    - PASSED: Zero fatal errors or critical warnings; eligible for institutional signoff.
    - WARNINGS: Minor formatting or advisory issues that should be corrected.
    - FAILED: Fatal violations (desk-rejection risks like undersized fonts or missing sections).
    """
    PASSED = "PASSED"
    WARNINGS = "WARNINGS"
    FAILED = "FAILED"


class FindingSeverity(str, enum.Enum):
    """
    Risk severity assigned to individual audit findings:
    - RED: Fatal desk-rejection violation (e.g. font < 10pt, margins < 0.75in).
    - YELLOW: High discrepancy or administrative warning (e.g. unclear budget row).
    - GREEN: Verified compliant metric passing institutional thresholds.
    """
    RED = "RED"
    YELLOW = "YELLOW"
    GREEN = "GREEN"


class FindingCategory(str, enum.Enum):
    """
    Functional compliance category for heuristic audit findings:
    - PAGE_LIMIT: Page count enforcement according to agency guidelines.
    - FONT_MARGIN: Sub-millimeter bounding box & font size distribution checks.
    - BUDGET: Financial line-item reconciliation against narrative claims.
    - MANDATORY_SECTION: Presence of required headers (References, Budget Justification).
    """
    PAGE_LIMIT = "PAGE_LIMIT"
    FONT_MARGIN = "FONT_MARGIN"
    BUDGET = "BUDGET"
    MANDATORY_SECTION = "MANDATORY_SECTION"


class AIPanelRecommendation(str, enum.Enum):
    """
    [Week 3] Simulated federal grant peer review panel recommendation:
    - FUND_WITH_DISTINCTION: Exceptional score (>= 90%) across all NSF/NIH criteria.
    - REVISE_AND_RESUBMIT: Viable proposal with minor narrative or impact deficits.
    - DO_NOT_RECOMMEND: Major structural or scientific deficiencies identified.
    """
    FUND_WITH_DISTINCTION = "FUND_WITH_DISTINCTION"
    REVISE_AND_RESUBMIT = "REVISE_AND_RESUBMIT"
    DO_NOT_RECOMMEND = "DO_NOT_RECOMMEND"


# ==============================================================================
# 1. USER ENTITY (Academic Researchers & SRO Officers)
# ==============================================================================

class User(Base):
    """
    Represents an authenticated academic faculty member or researcher.
    Protected with native bcrypt password hashing and RFC 6749 JWT token lifecycles.
    """
    __tablename__ = "users"

    # Universally unique identifier primary key
    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        index=True,
    )

    # Institutional email address (e.g. researcher@grantlens.dev)
    email: Mapped[str] = mapped_column(
        String(255),
        unique=True,
        nullable=False,
        index=True,
    )

    # Salted Bcrypt password hash string
    hashed_password: Mapped[str] = mapped_column(String(255), nullable=False)

    # Full institutional name of researcher
    full_name: Mapped[str] = mapped_column(String(255), nullable=False)

    # University or Research Organization
    institution: Mapped[str] = mapped_column(String(255), nullable=False, index=True)

    # Academic Department (e.g. Department of Computer Science)
    department: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)

    # Account status flag
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)

    # Timestamp of researcher account creation
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    # 1:N Relationship: A researcher owns multiple grant submissions
    submissions: Mapped[List["GrantSubmission"]] = relationship(
        "GrantSubmission",
        back_populates="user",
        cascade="all, delete-orphan",
    )


# ==============================================================================
# 2. GRANT SUBMISSION ENTITY
# ==============================================================================

class GrantSubmission(Base):
    """
    Central container entity for an uploaded grant pre-flight package.
    Links the solicitation guidelines, proposal manuscript, deterministic audit,
    and Gemini AI narrative review under a single trackable lifecycle.
    """
    __tablename__ = "grant_submissions"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        index=True,
    )

    # Foreign key referencing the submitting researcher
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    # Title of the grant proposal manuscript
    title: Mapped[str] = mapped_column(String(500), nullable=False)

    # Target funding agency solicitation identifier (e.g. NSF 24-500)
    funding_agency: Mapped[str] = mapped_column(String(255), nullable=False, index=True)

    # Overall lifecycle status (INGESTED, AUDITED, SIGNED_OFF)
    status: Mapped[str] = mapped_column(
        String(50),
        default="INGESTED",
        nullable=False,
    )

    # Submission timestamp
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    # Bidirectional ORM relationships
    user: Mapped["User"] = relationship("User", back_populates="submissions")

    documents: Mapped[List["Document"]] = relationship(
        "Document",
        back_populates="submission",
        cascade="all, delete-orphan",
    )

    audit_reports: Mapped[List["AuditReport"]] = relationship(
        "AuditReport",
        back_populates="submission",
        cascade="all, delete-orphan",
    )

    budget_items: Mapped[List["BudgetLineItem"]] = relationship(
        "BudgetLineItem",
        back_populates="submission",
        cascade="all, delete-orphan",
    )

    # [NEW Week 3] Relationship to Gemini AI Reviews (1:N or 1:1 historical reviews)
    ai_reviews: Mapped[List["AIReview"]] = relationship(
        "AIReview",
        back_populates="submission",
        cascade="all, delete-orphan",
    )


# ==============================================================================
# 3. DOCUMENT ARTIFACT ENTITY
# ==============================================================================

class Document(Base):
    """
    Stores physical file paths, SHA-256 verification hashes, and extracted
    metadata for both the agency solicitation and the proposal manuscript.
    """
    __tablename__ = "documents"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        index=True,
    )

    submission_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("grant_submissions.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    doc_type: Mapped[DocumentType] = mapped_column(
        Enum(DocumentType, name="document_type_enum"),
        nullable=False,
    )

    file_path: Mapped[str] = mapped_column(String(1024), nullable=False)
    file_hash: Mapped[str] = mapped_column(String(64), nullable=False)
    page_count: Mapped[int] = mapped_column(Integer, nullable=False)

    # JSON dictionary storing PyMuPDF font statistics, margins, and section trees
    extracted_metadata: Mapped[dict[str, Any]] = mapped_column(
        JSON,
        nullable=False,
        default=dict,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    submission: Mapped["GrantSubmission"] = relationship(
        "GrantSubmission",
        back_populates="documents",
    )

    __table_args__ = (
        Index("ix_documents_submission_doc_type", "submission_id", "doc_type"),
    )


